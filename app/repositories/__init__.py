"""仓储层（Repository）：把 SQL 查询从路由里挪出来。

为什么要有这一层
----------------
重构前 `routers/admin.py` 里散着 30+ 处 `session.exec(select(...))`，业务规则与
查询语句缠在一起：想改一个统计口径要翻遍路由文件，想写单测必须先起一个
HTTP 请求。仓储层把这些查询收拢成「按域命名的方法」，路由只负责
「入参校验 → 调仓储 → 序列化」。

约定
----
* 每个模块对应一个领域（统计 / 账户 / 订单 / 行情），不跨域 join；
* 所有聚合走 SQL（`func.count` / `func.sum` / `group_by`），不再把整表读进
  内存再 `sum` —— 数据量一上来，全表加载会把后台首屏拖死；
* 返回**朴素的 dict / 标量**，不返回 ORM 对象，避免调用方误用延迟属性。
"""
